//
// ★なぜこのファイルが在るか:
//   BB の σ 倍率(旧 1.5)は「計算(server/indicators.ts の 2箇所)」「パネルの列名(web)」
//   「AI へ渡す文脈のラベル(server/llm/scalpContext.ts)」「AI 許可文(server/llm/scalpPlan.ts)」の
//   4箇所に **数値と文字列で別々に手書き** されていた。片方だけ直せば「画面は 0.7σ・計算は 1.5σ」
//   という無言の食い違いが起きる(検知種別で実際に起きた事故と同じ形 = core/detectionKinds.ts の冒頭注記)。
//   ゆえに倍率とその表示ラベルはここだけに置き、server / web / llm は必ずここから読む。
//
// ★消費側(ここを変えたら影響する箇所・2026-08-15 に実態へ合わせて更新):
//   - server/indicators.ts             … bollinger() の既定倍率 / computeIndicators の算出
//   - server/bandwalk.ts               … バンドウォーク判定(価格 ≥ +σ / ≤ −σ。σ は indicators 経由)
//   - server/llm/scalpContext.ts       … AI へ渡す「テクニカル指標」ブロックのラベル(BB_BAND_LABEL)
//   - server/llm/scalpPlan.ts          … AI へのテクニカル許可文のラベル(BB_BAND_LABEL)
//   ※パネル(web/components/indicatorPanel.ts)は列名を %B / BW / BWhigh・low に差し替えたため
//     もうσのラベルを読まない。「消費側」に名前だけ残すと、消えた経路を在るものとして数えてしまう。

/** ボリンジャーバンドの σ 倍率。中央(SMA14)± BB_SIGMA×σ。
 *
 *  ★表示(パネル)と判定(バンドウォーク)は **同じ倍率を使う**(定数は意図的に1本にしてある)。
 *    判定用だけ深い σ にする案を実データで掃引したが(σ=0.7/1.0/1.3/1.5/2.0 × 窓/占有率/最小本数を
 *    それぞれ最適化・NIY=F 直近60日)、**どの σ でも「バンドウォーク中はその方向に伸びる」は
 *    統計的に確認できなかった**(発火後30/60分の順行率は全 230 セルで 44〜56%・|z|<1.96)。
 *    一方 σ を上げると持続性(2本キープ後の継続確率)は 81%→37% と壊れる。
 *    ゆえに「深い σ にすれば伸びが出る」という仮説は否定され、**表示と判定を分ける理由が無い**。
 *    分けてしまうと「画面は 0.7σ・AI には 1.5σ」という食い違いを生むだけなので1本のままにする。 */
export const BB_SIGMA = 0.7;

// ★BB_UPPER_LABEL / BB_LOWER_LABEL は 2026-08-15 に削除した。
//   パネルの列名が %B / BW / BWhigh・low に変わり、リポジトリ全体で参照が 0 になったため
//   (「上限/下限を別々に出す画面」がもう存在しない)。σ の表示は下の BB_BAND_LABEL だけが担う。

/** 「±0.7σ」形式のラベル(プロンプト/文脈ブロック用)。 */
export const BB_BAND_LABEL = `±${BB_SIGMA}σ`;

// ─── ★スクイーズ用バンド(2026-08-15 新設・上のσとは **別系列**) ───────────────
//
// ■ なぜ別に持つのか
//   上の BB_SIGMA(=0.7) は **バンドウォーク判定と AI プロンプトの文言** が共有している。
//   ここを 2σ に書き換えると、判定の意味とプロンプトの文字列が同時に変わり、
//   **実走中の質問文 A/B(v1 vs v2)の標本が割れる**(プロンプトが変われば指紋が変わる)。
//   スクイーズ/バルジは「バンド幅の伸縮」を見る別の道具なので、**別の定数として並べて置く**。
//
// ■ 消費側
//   - server/indicators.ts             … computeSqueezeSeries / bandwidthExtremes
//   - server/detect/registry.ts        … スクイーズ/バルジの検知
//   - web/components/indicatorPanel.ts … %B / BW / BWhigh・low の表示
//   ★上のバンド(14本/0.7σ)の消費側は1つも変えない。

