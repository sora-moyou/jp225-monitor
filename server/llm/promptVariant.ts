// ─── 質問文の変種(PromptVariant) ─────────────────────────────────────────
//
// ★これは **決済仕様の変種(ExitVariant)とは別の軸** である。混ぜないこと。
//   - ExitVariant  … AI に教える「決済の仕様」を変える(プロンプトの決済ブロックだけが変わる)
//   - PromptVariant … AI に投げる「質問文そのもの」を変える(user プロンプトの本体が変わる)
//
// なぜ足すか(2026-08-13):
//   決済仕様の A/B(current vs candidate-a)は 08-10〜08-12 の3セッション・実測で
//   **どの指標も動かなかった**(両レッグ同幅 88.1% vs 87.9% / LC幅中央値 60 vs 60 /
//   エントリー率 70.2% vs 71.4%)。測っていたのは「決済の説明を変えたら入り方が変わるか」で、
//   答えは「変わらない」。よってその腕は畳み、**質問文** を候補に載せ替える。
//
//   主指標は「両レッグ同幅率」(指値レッグとブレイク新規レッグの LC幅が同じ数値になる割合)。
//   実測 87〜92% で、これは「幅を節目から導いていない」ことの代理指標。現行 v1 は 5,475文字・
//   ★24個まで肥大しており、規則を足すたびに失敗が **移動** しただけだった(下限55固着 → 中間60固着)。
//   v2 は禁止を並べず「システムの分担」を書く。効くかどうかは語りでなく上の率で決める。
//
//   ★★★ v2 を腕に戻す日に必ず読むこと(v0.9.84) ★★★
//     戦略ラベル(strategy / strategyWhy)は **v1 系の共通の土台**(scalpJsonInstruction)にだけ入っている。
//     v2 は自前の JSON 契約を持ち、buildScalpPlan は v2 のとき jsonInstruction を足さない
//     (契約が2つ並ぶと「短くした」はずの質問文が v1 の分量に戻るため)。
//     ⇒ **v2 を腕に載せると、その腕の標本だけ strategy が無音で欠測する**。
//     欠測は「ラベルを書かなかった」と見分けが付かないので、戻す前に buildScalpQuestionV2 の
//     JSON 契約へ scalpStrategyContract() 相当を入れるか、欠測を承知で測ると明記すること。
//
// ★'v1' が既定。**省略時は完全に従来どおり**(稼働機・実取引につながる経路は byte 不変)。
//
// ─── 'v1d'(2026-08-17 追加) = v1 マイナス「最低距離」。動かす変数は **1つだけ** ────────────
//
//   設計書: docs/superpowers/specs/2026-08-17-signal-constraints-design.md(制約を3層へ分ける)。
//   その §8「移行の順序」の1番目=**層1(執行)を直す**の第一手が、この腕である。
//
//   ■ 外すもの: 「指値・ブレイク新規を現在値から最低50円離す」。**この記述だけ**。
//     プロンプト中の3箇所(質問文②の括弧 / strategySpec のエントリー箇条書き /
//     バンドウォーク注記の免除文①)から同時に消す。3箇所とも **同じ1つの規則** の掲載なので、
//     1箇所だけ残すと「消したはずの規則が別の場所から効く」=何を測ったのか言えなくなる。
//
//   ■ 残すもの: 距離の **上限**(片レッグ200円 / 両レッグ幅400円)は今回は残す。
//     設計書は上限もプロンプトから外す方針だが、同時に2つ動かすと帰属できない(★1コミット1変数)。
//
//   ■ なぜ測るか(実測)
//     ・89.8% の断面で「節目の5〜10円内側」と最低距離50円が **両立しない**(合法解が存在しない)。
//     ・2,222レッグのうち **72.0% が距離を破り**、LC下限を破ったレッグは **0件**。
//       ＝ AI は例外なく距離のほうを捨てていた(印字2回・自己検算に載らない側)。
//     ・v2(距離ルールを書かない系統)と比べても距離の中央値は 25円 で **同一** =
//       この記述は書いても書かなくても出力を変えていない疑いが濃い。
//       ただし v2 は質問文を全面的に書き換えているので **1変数の対照になっていない**。
//     ⇒ v1d は「**距離の記述だけ**を外したら、AI は節目に素直に置くようになるか」を測る腕。
//
//   ■ 主指標(解析側で見る。コードでは何も判定しない)
//     現在値からの距離の分布 / **LC幅の相異なる値の種類数** / 両レッグ同幅率 / none 率。
//     ★LC幅は「平均」では見ない(下限＋一定への移行を平均は見逃す)。
//
//   ★実行時には稼働機へ接続しない。'v1d' は候補腕から降ろされ(2026-08-18)、腕は 'v1e' に載せ替わったが、
//     過去の台帳(prompt-v1d 行)を読めるように語彙・omitMinDistance フラグ・テストはそのまま残す。
//
// ─── 'v1e'(2026-08-18 追加) = v1 マイナス「距離の上限」。動かす変数は **1つだけ** ────────────
//
//   v1d(最低距離50円を外す)は実測で **悪化**(両レッグ同幅率 76.4% → 84.7% / 距離<50 の割合
//   58.4% → 66.4%[McNemar p=0.0037] / 距離の中央値 40円 → 30円 / LC幅=55固着 36.1% → 44.3%)。
//   ⇒「最低距離50円」の記述は、コードの強制(10円)とは別に「置き方の誘導」として効いている。**残す。**
//
//   ■ 外すもの: 「指値・ブレイク新規の価格差[両者の幅]は400円以内 / 片方だけは現在値から200円以内」
//     という **距離の上限** の記述。プロンプト中の3箇所(質問文②の距離ブロック / system prompt の
//     【指値・ブレイク新規の距離(必須)】箇条書き / strategySpec の同箇条書き)から同時に消す。
//     ★range 専用の距離規則(上下2本400円/片面200円)は既に rangeEnabled で条件化済みで、
//       このフラグの対象外(range が別に持つ規則なので触らない=1変数を保つ)。
//
//   ■ 残すもの: 最低距離50円の記述(3箇所)は上の実測により **残す**。同時に2つ動かすと
//     帰属できない(★1コミット1変数)。
//
//   ■ なぜ測るか
//     v0.9.83 で「死んだ記述だけ」(range無効時の距離規則・委任時の「自動見送り」の一文)を消したところ、
//     v1 自身が改善した可能性がある(距離<50 が 72〜77% → 58.4%、距離の中央値 25円 → 40円)。
//     ただし日をまたいだ比較で交絡しており断定できない。
//     仮説: 競合する距離の数値(200/400)が、生きている距離規則(節目からの5〜10円)を押しのけていた。
//     ⇒ v1e は「距離の **上限** の記述だけを外したら、AI はどう変わるか」を測る腕
//       (改善なら「競合する数値が押しのけていた」を支持/悪化ならその数値も誘導として働いていたことになる)。
//
//   ■ 主指標(v1d と同じ): 現在値からの距離の分布 / LC幅の相異なる値の種類数 / 両レッグ同幅率 / none率。
//
//   ★実行時には稼働機へ接続しない。生成器の候補腕(server/generator/cycle.ts)だけが 'v1e' を送る。

export type PromptVariant = 'v1' | 'v2' | 'v1d' | 'v1e';

/** 受理する変種名の一覧(エラーメッセージの生成もここから作る=一覧と実装がずれない)。 */
export const PROMPT_VARIANTS = ['v1', 'v2', 'v1d', 'v1e'] as const;

/** 省略時の質問文。既存の呼び出し元(シグナルエンジン・手動診断・trade2)は必ずこれ。 */
export const DEFAULT_PROMPT_VARIANT: PromptVariant = 'v1';

export type NormalizePromptVariantResult =
  | { ok: true; variant: PromptVariant }
  | { ok: false; error: string };

/** 外部入力(HTTP body/query)を PromptVariant へ正規化する純関数。
 *  - 未指定 / null / 空文字 → 'v1'(省略時は従来どおり)
 *  - PROMPT_VARIANTS のいずれか → そのまま
 *  - それ以外 → **エラー(400)**。
 *
 *  ★未知の値を黙って 'v1' に倒さない理由は exitVariant と同じ: 「v2 で生成した」つもりの標本が
 *    実は v1 になり、A/B の差が消えたことに誰も気づけない(=実験が静かに壊れる)。 */
export function normalizePromptVariant(v: unknown): NormalizePromptVariantResult {
  if (v === undefined || v === null || v === '') return { ok: true, variant: DEFAULT_PROMPT_VARIANT };
  if (typeof v === 'string' && (PROMPT_VARIANTS as readonly string[]).includes(v)) {
    return { ok: true, variant: v as PromptVariant };
  }
  const got = typeof v === 'string' ? v.slice(0, 32) : typeof v;
  return { ok: false, error: `promptVariant は ${PROMPT_VARIANTS.map(n => `'${n}'`).join(' | ')} のみ(受信: ${got})` };
}

/** ★分析用の **予算の帳簿を分ける単位**。
 *  従来は決済仕様の変種名そのものだった(腕=変種だったため)。質問文の A/B では両腕とも
 *  exitVariant='current' を送るので、変種名だけを鍵にすると **2本の腕が1つの財布を共有** し、
 *  先着の腕が取引日の残りを食い切って標本が時間帯に偏る(=既知最大の交絡がそのまま入る)。
 *  よって鍵は (決済変種 × 質問文変種) にする。v1 のときは従来と同じ文字列になる(過去の期と繋がる)。 */
export function generatorArmKey(exitVariant: string, promptVariant: PromptVariant = DEFAULT_PROMPT_VARIANT): string {
  return promptVariant === DEFAULT_PROMPT_VARIANT ? exitVariant : `${exitVariant}+${promptVariant}`;
}
